assert.ok(formatExchangeDate(overlap[0].instant).endsWith('(UTC+02:00)'));
assert.ok(formatExchangeDate(overlap[1].instant).endsWith('(UTC+01:00)'));
assert.ok(formatExchangeDate('2026-10-25T01:30:45.123Z').endsWith('(UTC+01:00)'));
const ordinary=new Date('2026-09-08T08:05:00Z');
assert.equal(formatExchangeDate(ordinary.toISOString()),new Intl.DateTimeFormat('fr-FR',{timeZone:'Europe/Paris',dateStyle:'medium',timeStyle:'short'}).format(ordinary));
assert.equal(resolveParisDate('2026-10-25T02:30',overlap[1].instant).instant,overlap[1].instant);
assert.ok('error' in resolveParisDate('2026-10-25T02:30','2026-10-25T03:30:00.000Z'));
for(const date of ['2026-02-30T12:00','2026-01-01T24:00','2026-01-01T12:60','invalid'])assert.deepEqual(parisCandidates(date),[]);
assert.equal(parisLocalNow(new Date('2026-09-08T08:05:00Z')),'2026-09-08T10:05');
